/**
 * @param {string} anchor
 * @returns {HangulOrthographyArticle | undefined}
 */
export function findHangulOrthographyArticle(anchor) {
  return HANGUL_ORTHOGRAPHY_ARTICLES.find((a) => a.anchor === anchor);
}

/**
 * @param {number} number
 * @returns {string}
 */
export function hangulOrthographyAnchor(number) {
  return `art-${Number(number)}`;
}

/**
 * 국립국어원 고시 목차와 같이 본문 → 장 → 절 → 항으로 묶는다.
 * @param {HangulOrthographyArticle[]} [articles]
 * @returns {{ chapter: string, sections: { section: string, articles: HangulOrthographyArticle[] }[] }[]}
 */
export function groupHangulOrthographyTree(articles = HANGUL_ORTHOGRAPHY_ARTICLES) {
  /** @type {{ chapter: string, sections: { section: string, articles: HangulOrthographyArticle[] }[] }[]} */
  const groups = [];
  for (const art of articles) {
    let chapter = groups[groups.length - 1];
    if (!chapter || chapter.chapter !== art.chapter) {
      chapter = { chapter: art.chapter, sections: [] };
      groups.push(chapter);
    }
    const sectionKey = art.section || '';
    let section = chapter.sections[chapter.sections.length - 1];
    if (!section || section.section !== sectionKey) {
      section = { section: sectionKey, articles: [] };
      chapter.sections.push(section);
    }
    section.articles.push(art);
  }
  return groups;
}
